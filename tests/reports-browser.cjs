const assert = require("node:assert/strict");
const fs = require("node:fs/promises");
const path = require("node:path");
const { pathToFileURL } = require("node:url");
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || "playwright-core");

(async () => {
  const base = process.env.CODEFORM_URL || "http://127.0.0.1:7334";
  const artifacts = path.resolve(__dirname, "..", ".codeform", "browser-artifacts");
  await fs.mkdir(artifacts, { recursive: true });
  const browser = await chromium.launch({ headless: true });
  try {
    const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, acceptDownloads: true });
    const errors = [];
    page.on("pageerror", error => errors.push(error.message));
    const bootstrap = await (await page.request.get(base + "/api/bootstrap")).json();
    const snapshot = bootstrap.snapshots.find(s => s.repository.name === "inference-exchange");
    const root = `${base}/api/v1/snapshots/${snapshot.id}`;
    const before = await (await page.request.get(root + "/workflows")).json();
    const owner = before.find(r => r.mode !== "preview" && r.state === "awaiting_review");
    assert.ok(owner);
    await page.goto(`${base}/#${snapshot.id}/proofs`);
    await page.getByRole("heading", { name: "Formal model adapter needed" }).waitFor();
    assert.equal(await page.getByRole("button", { name: "Check proofs with Lean" }).isDisabled(), true);
    await page.getByRole("button", { name: "Read the review report", exact: true }).click();
    await page.getByRole("heading", { name: "What each tab shows" }).waitFor();
    const popup = page.waitForEvent("popup");
    await page.getByRole("link", { name: "Open readable report" }).click();
    const reportPage = await popup;
    reportPage.on("pageerror", error => errors.push(error.message));
    await reportPage.waitForLoadState("networkidle");
    assert.ok((await reportPage.locator("article").innerText()).includes("Supported obligations: 0"));
    assert.ok((await reportPage.locator("article").innerText()).includes("not owner-approved"));
    await reportPage.getByRole("heading", { name: "Proposed mathematical specifications", exact: true }).waitFor();
    assert.ok(await reportPage.locator(".report-math .katex").count() > 10);
    assert.ok(await reportPage.locator(".report-diagram svg").count() > 0);
    await reportPage.screenshot({ path: path.join(artifacts, "inference-review-report.png"), fullPage: true });
    const downloadReady = reportPage.waitForEvent("download");
    await reportPage.getByRole("link", { name: "Save standalone HTML" }).click();
    const download = await downloadReady;
    const offlinePath = path.join(artifacts, "inference-review-report.html");
    await download.saveAs(offlinePath);
    const offline = await browser.newPage({ acceptDownloads: true });
    offline.on("pageerror", error => errors.push(error.message));
    const networkRequests = [];
    offline.on("request", request => { if (/^https?:/.test(request.url())) networkRequests.push(request.url()); });
    await offline.goto(pathToFileURL(offlinePath).href);
    assert.ok(await offline.locator(".report-math .katex").count() > 10);
    const extractedDownload = offline.waitForEvent("download");
    await offline.getByRole("link", { name: "Download JSON companion" }).click();
    const jsonPath = path.join(artifacts, "inference-review-report.json");
    await (await extractedDownload).saveAs(jsonPath);
    const report = JSON.parse(await fs.readFile(jsonPath, "utf-8"));
    assert.equal(report.snapshot_id, snapshot.id);
    assert.equal(report.workflow.state, "preview_complete");
    assert.equal(report.verification_coverage.supported_obligations, 0);
    assert.equal(report.owner_review[0].state, "awaiting_review");
    assert.equal(report.analysis.sources.length, snapshot.summary.files);
    assert.deepEqual(networkRequests, []);
    await offline.setViewportSize({ width: 390, height: 844 });
    assert.equal(await offline.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
    await offline.screenshot({ path: path.join(artifacts, "inference-review-report-mobile.png"), fullPage: true });
    const after = await (await page.request.get(root + `/workflows/${owner.id}`)).json();
    assert.deepEqual(after.events, owner.events);
    assert.equal(after.state, "awaiting_review");
    assert.deepEqual(errors, []);
    console.log("Report browser passed: tabs, unsupported proof state, preview mathematics, source/diagram, offline LaTeX, embedded JSON, mobile, and untouched live gate.");
  } finally {
    await browser.close();
  }
})().catch(error => { console.error(error); process.exitCode = 1; });
