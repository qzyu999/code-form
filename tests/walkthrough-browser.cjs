const assert = require("node:assert/strict");
const fs = require("node:fs/promises");
const path = require("node:path");
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || "playwright-core");

(async () => {
  const base = process.env.CODEFORM_URL || "http://127.0.0.1:7333";
  const artifacts = path.resolve(__dirname, "..", ".codeform", "browser-artifacts");
  await fs.mkdir(artifacts, { recursive: true });
  const browser = await chromium.launch({ headless: true });
  try {
    const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
    const errors = [], externalRequests = [], badResponses = [];
    page.on("pageerror", error => errors.push(error.message));
    page.on("console", message => { if (message.type() === "error" && !message.text().includes("400 (Bad Request)")) errors.push(message.text()); });
    page.on("response", response => { if (response.status() >= 400) badResponses.push([response.status(), response.url()]); });
    page.on("request", request => { if (!request.url().startsWith(base)) externalRequests.push(request.url()); });
    const bootstrap = await (await page.request.get(base + "/api/bootstrap")).json();
    const transfer = bootstrap.snapshots.find(s => s.repository.name === "verified-transfer");
    const workflow = bootstrap.snapshots.find(s => s.repository.name === "verified-workflow");
    const payment = bootstrap.snapshots.find(s => s.repository.name === "payment-service");
    await page.goto(`${base}/#${transfer.id}`);
    await page.getByRole("heading", { name: "System walkthrough", exact: true }).waitFor();
    await page.locator(".katex").first().waitFor();
    assert.equal(await page.locator(".math-fallback").count(), 0);
    await page.locator(".walk-origin [data-walk-captured-source]").click();
    await page.getByRole("heading", { name: "README.md", exact: true }).waitFor();
    await page.getByRole("button", { name: "Close inspector", exact: true }).click();
    await page.locator(".notation-tile").first().click();
    await page.getByRole("heading", { name: "Source balance", exact: true }).waitFor();
    await page.getByRole("button", { name: "Close notation explanation" }).click();
    await page.locator("[data-walk-preset=overdraft]").click();
    await page.getByText("This example violates an intended property", { exact: true }).waitFor();
    await page.getByRole("button", { name: "transfer_guarded", exact: true }).click();
    await page.locator("[data-walk-preset=overdraft]").click();
    await page.getByText("The model rejects this request", { exact: true }).waitFor();
    await page.locator("[data-walk-preset=assumption]").click();
    await page.getByText("This input is outside the stated invariant assumptions", { exact: true }).waitFor();
    await page.locator("#walk-source").fill("1.5");
    await page.getByRole("button", { name: "Run model example" }).click();
    await page.locator("#scenario-error").filter({ hasText: "Input rejected" }).waitFor();
    await page.locator("[data-walk-preset=normal]").click();
    await page.locator(".walk-proof .proof-details summary").first().click();
    await page.locator(".walk-proof .lean-preview").first().waitFor();
    await page.screenshot({ path: path.join(artifacts, "math-first-walkthrough.png"), fullPage: true });
    const downloadWait = page.waitForEvent("download");
    await page.getByRole("button", { name: "Export walkthrough" }).click();
    await (await downloadWait).saveAs(path.join(artifacts, "walkthrough.json"));
    const report = JSON.parse(await fs.readFile(path.join(artifacts, "walkthrough.json"), "utf8"));
    assert.equal(report.snapshot_id, transfer.id);
    assert.equal(report.models.length, 2);
    await page.selectOption("#snapshot-select", workflow.id);
    await page.locator("[data-walk-preset=terminal]").click();
    await page.getByText("The example preserves the applicable properties", { exact: true }).waitFor();
    await page.setViewportSize({ width: 390, height: 844 });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
    await page.screenshot({ path: path.join(artifacts, "math-first-walkthrough-mobile.png"), fullPage: true });
    await page.selectOption("#snapshot-select", payment.id);
    await page.getByRole("heading", { name: "Mathematical reconstruction is not available for this repository" }).waitFor();
    assert.equal(await page.locator(".walk-proof").count(), 0);
    assert.deepEqual(errors, []);
    assert.deepEqual(externalRequests, [], "Renderer and fonts must be served locally.");
    assert.equal(badResponses.length, 1, "Only the deliberately invalid scenario request may fail.");
    assert.equal(badResponses[0][0], 400);
    assert.equal(badResponses[0][1].endsWith("/scenarios"), true);
    console.log("Walkthrough browser passed: default entry, local LaTeX, glossary, exact examples, rejection, assumptions, Lean links, export, workflow, fallback, and mobile.");
  } finally {
    await browser.close();
  }
})().catch(error => { console.error(error); process.exitCode = 1; });
